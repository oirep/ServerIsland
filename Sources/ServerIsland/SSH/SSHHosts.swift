import Foundation

/// 手动填写的服务器和跳板机：生成一份 App 私有的 ssh 配置，只在 ServerIsland 自己调用 ssh 时
/// 通过 `-F` 使用；用户的 `~/.ssh/config` 一个字都不改（私有配置末尾 Include 它和系统配置）。
///
/// - 手动填写的服务器用别名 `si-<UUID>`，块里写 HostName / User / Port / IdentityFile；
/// - 设了跳板机的服务器，在它的块里写 ProxyCommand：用同一份配置 ssh 到跳板机再 `-W` 转发。
///   跳板机如果已经登录（主连接还在），转发直接走它的主连接，不用再输密码；
///   跳板机还有跳板机时，内层 ssh 读到的还是这份配置，自然一跳一跳接下去。
/// - ProxyCommand 里给内层 ssh 设置 `SERVERISLAND_ASKPASS_HOSTID`，弹窗就知道是哪一跳在要密码。
enum SSHHosts {
    private static let lock = NSLock()
    private static var hosts: [UUID: HostConfig] = [:]
    private static var written = ""
    /// 自检 / 预览渲染时为 false：不能覆盖正在运行的 App 的配置文件。
    private static var writes = false

    static var configPath: String {
        // 测试用的另一份设置（SERVERISLAND_CONFIG_DIR）不能和正在运行的 App 共用一个文件。
        if let dir = ProcessInfo.processInfo.environment["SERVERISLAND_CONFIG_DIR"], !dir.isEmpty { return dir + "/ssh_config" }
        return SSHRunner.controlDirectory + "/ssh_config"
    }

    /// 配置变化时调用：更新索引，内容有变化才重写文件。
    static func update(_ list: [HostConfig], write: Bool = true) {
        lock.lock(); defer { lock.unlock() }
        hosts = Dictionary(list.map { ($0.id, $0) }, uniquingKeysWith: { a, _ in a })
        writes = write
        writeIfNeeded()
    }

    static func host(_ id: UUID) -> HostConfig? {
        lock.lock(); defer { lock.unlock() }
        return hosts[id]
    }

    /// ssh 命令行上的目标名。
    static func target(_ host: HostConfig) -> String {
        host.isManual ? "si-" + host.id.uuidString : host.alias
    }

    /// 这台机器是否要用私有配置（手动填写或经跳板机）。
    static func needsPrivateConfig(_ host: HostConfig) -> Bool {
        host.isManual || host.jumpHostID != nil
    }

    /// 从近到远的跳板机列表（不含自己）。遇到环或找不到的跳板机就停下。
    static func jumpChain(_ host: HostConfig) -> [HostConfig] {
        lock.lock(); defer { lock.unlock() }
        return chain(host, in: hosts)
    }

    static func chain(_ host: HostConfig, in all: [UUID: HostConfig]) -> [HostConfig] {
        var out: [HostConfig] = []
        var seen: Set<UUID> = [host.id]
        var next = host.jumpHostID
        while let id = next, let j = all[id], seen.insert(id).inserted {
            out.append(j)
            next = j.jumpHostID
        }
        return out
    }

    /// 选跳板机时可选的服务器：不能是自己，也不能是"以自己为跳板"的机器（会成环）。
    static func jumpCandidates(for host: HostConfig, among list: [HostConfig]) -> [HostConfig] {
        let all = Dictionary(list.map { ($0.id, $0) }, uniquingKeysWith: { a, _ in a })
        return list.filter { c in
            c.id != host.id && !chain(c, in: all).contains { $0.id == host.id }
        }
    }

    /// 连接到 `host` 时显示用的"user@地址:端口"。
    static func summary(_ host: HostConfig) -> String {
        guard host.isManual else { return host.alias }
        var s = host.user.isEmpty ? "" : host.user + "@"
        s += host.hostName.trimmingCharacters(in: .whitespaces)
        if let p = host.port, p != 22 { s += ":\(p)" }
        return s
    }

    // MARK: - 生成配置

    static func render(_ list: [HostConfig], path: String, controlPath: (HostConfig) -> String) -> String {
        let all = Dictionary(list.map { ($0.id, $0) }, uniquingKeysWith: { a, _ in a })
        var out = "# Generated by ServerIsland. Do not edit: it is rewritten whenever the settings change.\n"
        out += "# Used only by ServerIsland (ssh -F); ~/.ssh/config is included below and never modified.\n\n"
        var done = Set<String>()
        for h in list where needsPrivateConfig(h) {
            // 命令行上的 user@host 只按 host 部分匹配 Host 块
            var name = target(h)
            if !h.isManual, let at = name.lastIndex(of: "@") { name = String(name[name.index(after: at)...]) }
            guard done.insert(name).inserted else { continue }
            out += "Host \(name)\n"
            if h.isManual {
                var addr = h.hostName.trimmingCharacters(in: .whitespaces)
                var user = h.user.trimmingCharacters(in: .whitespaces)
                // 允许在地址里直接写 user@host
                if user.isEmpty, let at = addr.lastIndex(of: "@") {
                    user = String(addr[..<at]); addr = String(addr[addr.index(after: at)...])
                }
                out += "  HostName \(quote(addr))\n"
                if !user.isEmpty { out += "  User \(quote(user))\n" }
                if let p = h.port, p > 0 { out += "  Port \(p)\n" }
                let key = h.identityFile.trimmingCharacters(in: .whitespaces)
                if !key.isEmpty {
                    out += "  IdentityFile \(quote(key))\n"
                    out += "  IdentitiesOnly yes\n"
                }
            }
            if let jid = h.jumpHostID, let j = all[jid], !chain(h, in: all).isEmpty {
                // %h %p 由外层 ssh 展开；%%C 留给内层 ssh 算跳板机自己的主连接路径。
                let cp = controlPath(j).replacingOccurrences(of: "%", with: "%%")
                out += "  ProxyCommand env \(AskPass.envHostID)=\(j.id.uuidString) /usr/bin/ssh -F \(SSHRunner.shellQuote(path))"
                out += " -o ControlMaster=no -o ControlPath=\(SSHRunner.shellQuote(cp)) -o ConnectTimeout=15"
                out += " -W '[%h]:%p' \(SSHRunner.shellQuote(target(j)))\n"
            }
            out += "\n"
        }
        out += "Match all\n"
        // 开发 / 测试用：先读一份额外配置（比如测试用的 known_hosts），不碰用户的 ~/.ssh。
        if let extra = ProcessInfo.processInfo.environment["SERVERISLAND_SSH_EXTRA_CONFIG"], !extra.isEmpty {
            out += "Include \(quote(extra))\n"
        }
        out += "Include ~/.ssh/config\n"
        out += "Include /etc/ssh/ssh_config\n"
        return out
    }

    private static func quote(_ v: String) -> String {
        v.contains(where: { $0 == " " || $0 == "\t" }) ? "\"" + v.replacingOccurrences(of: "\"", with: "") + "\"" : v
    }

    private static func writeIfNeeded() {
        guard writes else { return }
        let text = render(Array(hosts.values).sorted { $0.id.uuidString < $1.id.uuidString },
                          path: configPath, controlPath: SSHRunner.controlPath(for:))
        guard text != written else { return }
        SSHRunner.ensureControlDirectory()
        let url = URL(fileURLWithPath: configPath)
        do {
            try text.write(to: url, atomically: true, encoding: .utf8)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            written = text
        } catch {
            NSLog("ServerIsland: cannot write ssh config: \(error)")
        }
    }

    /// /tmp 下的文件可能被系统清掉：每次用之前确认一下。
    static func ensureWritten() {
        lock.lock(); defer { lock.unlock() }
        if (try? String(contentsOfFile: configPath, encoding: .utf8)) != written { written = "" }
        writeIfNeeded()
    }
}
