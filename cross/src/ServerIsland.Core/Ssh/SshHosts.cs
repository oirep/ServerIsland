namespace ServerIsland.Core.Ssh;

/// 手动填写的服务器和跳板机（和 Mac 版 SSHHosts.swift 一致）。
/// - 系统 ssh：生成一份 App 私有的 ssh 配置，只在 ServerIsland 自己调用 ssh 时用 `-F` 指定；
///   末尾 Include 用户和系统的配置，用户的 ~/.ssh/config 一个字都不改。
///   手动填写的服务器用别名 `si-UUID`；设了跳板机的服务器在块里写 ProxyCommand（内层 ssh 读同一份配置，
///   并复用跳板机自己的主连接），环境变量 SERVERISLAND_ASKPASS_HOSTID 让弹窗知道是哪一跳在要密码。
/// - 内置 SSH（SSH.NET）：直接按这里的跳板机链一跳一跳转发，跳板机已登录时复用它的连接。
public static class SshHosts
{
    static readonly object Gate = new();
    static Dictionary<Guid, HostConfig> _hosts = [];
    static string _written = "";
    /// 自检 / 预览渲染时为 false：不能覆盖正在运行的 App 的配置文件。
    static bool _writes;

    public const string AskPassHostIdEnv = "SERVERISLAND_ASKPASS_HOSTID";

    public static string ConfigPath =>
        Environment.GetEnvironmentVariable("SERVERISLAND_CONFIG_DIR") is { Length: > 0 } dir
            ? Path.Combine(dir, "ssh_config")
            : OpenSshTransport.ControlDirectory + "/ssh_config";

    public static void Update(List<HostConfig> list, bool write = true)
    {
        lock (Gate)
        {
            _hosts = list.GroupBy(h => h.Id).ToDictionary(g => g.Key, g => g.First());
            _writes = write;
            WriteIfNeeded();
        }
    }

    public static HostConfig? Host(Guid id)
    {
        lock (Gate) return _hosts.GetValueOrDefault(id);
    }

    /// ssh 命令行上的目标名。
    public static string Target(HostConfig h) => h.IsManual ? "si-" + Upper(h.Id) : h.Alias;

    public static bool NeedsPrivateConfig(HostConfig h) => h.IsManual || h.JumpHostID != null;

    /// 从近到远的跳板机列表（不含自己）。遇到环或找不到的跳板机就停下。
    public static List<HostConfig> JumpChain(HostConfig h)
    {
        lock (Gate) return Chain(h, _hosts);
    }

    public static List<HostConfig> Chain(HostConfig h, IReadOnlyDictionary<Guid, HostConfig> all)
    {
        var outList = new List<HostConfig>();
        var seen = new HashSet<Guid> { h.Id };
        var next = h.JumpHostID;
        while (next is { } id && all.TryGetValue(id, out var j) && seen.Add(id))
        {
            outList.Add(j);
            next = j.JumpHostID;
        }
        return outList;
    }

    /// 选跳板机时可选的服务器：不能是自己，也不能是"以自己为跳板"的机器（会成环）。
    public static List<HostConfig> JumpCandidates(HostConfig h, IEnumerable<HostConfig> list)
    {
        var all = list.GroupBy(x => x.Id).ToDictionary(g => g.Key, g => g.First());
        return all.Values.Where(c => c.Id != h.Id && !Chain(c, all).Any(x => x.Id == h.Id)).ToList();
    }

    /// 显示用的"user@地址:端口"。
    public static string Summary(HostConfig h)
    {
        if (!h.IsManual) return h.Alias;
        var s = h.User.Trim().Length == 0 ? "" : h.User.Trim() + "@";
        s += h.HostName.Trim();
        if (h.Port is { } p && p != 22) s += ":" + p;
        return s;
    }

    /// 手动地址拆成 (user, host)：允许直接写 user@host。
    public static (string User, string Host) SplitAddress(HostConfig h)
    {
        var addr = h.HostName.Trim();
        var user = h.User.Trim();
        int at = addr.LastIndexOf('@');
        if (at >= 0)
        {
            if (user.Length == 0) user = addr[..at];
            addr = addr[(at + 1)..];
        }
        return (user, addr);
    }

    static string Upper(Guid g) => g.ToString("D").ToUpperInvariant();

    // MARK: 生成配置（系统 ssh）

    public static string Render(IEnumerable<HostConfig> list, string path, Func<HostConfig, string> controlPath)
    {
        var hosts = list.ToList();
        var all = hosts.GroupBy(h => h.Id).ToDictionary(g => g.Key, g => g.First());
        var sb = new System.Text.StringBuilder();
        sb.Append("# Generated by ServerIsland. Do not edit: it is rewritten whenever the settings change.\n");
        sb.Append("# Used only by ServerIsland (ssh -F); ~/.ssh/config is included below and never modified.\n\n");
        var done = new HashSet<string>();
        foreach (var h in hosts.Where(NeedsPrivateConfig))
        {
            // 命令行上的 user@host 只按 host 部分匹配 Host 块
            var name = Target(h);
            if (!h.IsManual && name.LastIndexOf('@') is var at and >= 0) name = name[(at + 1)..];
            if (!done.Add(name)) continue;
            sb.Append($"Host {name}\n");
            if (h.IsManual)
            {
                var (user, addr) = SplitAddress(h);
                sb.Append($"  HostName {Quote(addr)}\n");
                if (user.Length > 0) sb.Append($"  User {Quote(user)}\n");
                if (h.Port is { } p && p > 0) sb.Append($"  Port {p}\n");
                var key = h.IdentityFile.Trim();
                if (key.Length > 0)
                {
                    sb.Append($"  IdentityFile {Quote(key)}\n");
                    sb.Append("  IdentitiesOnly yes\n");
                }
            }
            if (h.JumpHostID is { } jid && all.TryGetValue(jid, out var j) && Chain(h, all).Count > 0)
            {
                // %h %p 由外层 ssh 展开；%%C 留给内层 ssh 算跳板机自己的主连接路径。
                var cp = controlPath(j).Replace("%", "%%");
                sb.Append($"  ProxyCommand env {AskPassHostIdEnv}={Upper(j.Id)} {OpenSshTransport.SshPath} -F {ShellQuote(path)}");
                sb.Append($" -o ControlMaster=no -o ControlPath={ShellQuote(cp)} -o ConnectTimeout=15");
                sb.Append($" -W '[%h]:%p' {ShellQuote(Target(j))}\n");
            }
            sb.Append('\n');
        }
        sb.Append("Match all\n");
        // 开发 / 测试用：先读一份额外配置（比如测试用的 known_hosts），不碰用户的 ~/.ssh。
        if (Environment.GetEnvironmentVariable("SERVERISLAND_SSH_EXTRA_CONFIG") is { Length: > 0 } extra)
            sb.Append($"Include {Quote(extra)}\n");
        sb.Append("Include ~/.ssh/config\n");
        sb.Append("Include /etc/ssh/ssh_config\n");
        return sb.ToString();
    }

    public static string ShellQuote(string s) => "'" + s.Replace("'", "'\\''") + "'";

    static string Quote(string v) => v.Contains(' ') || v.Contains('\t') ? "\"" + v.Replace("\"", "") + "\"" : v;

    static void WriteIfNeeded()
    {
        // Windows 自带的 OpenSSH 不支持 ControlMaster，系统 ssh 在那里只按别名连接（手动 / 跳板机走内置 SSH）。
        if (!_writes || !OpenSshTransport.SupportsControlMaster) return;
        var text = Render(_hosts.Values.OrderBy(h => Upper(h.Id), StringComparer.Ordinal), ConfigPath, OpenSshTransport.ControlPathFor);
        if (text == _written) return;
        try
        {
            OpenSshTransport.EnsureControlDirectory();
            File.WriteAllText(ConfigPath, text);
            File.SetUnixFileMode(ConfigPath, UnixFileMode.UserRead | UnixFileMode.UserWrite);
            _written = text;
        }
        catch (Exception e) { DebugLog.Log("写 ssh 配置失败：" + e.Message); }
    }

    /// /tmp 下的文件可能被系统清掉：每次用之前确认一下。
    public static void EnsureWritten()
    {
        lock (Gate)
        {
            string? current = null;
            try { current = File.ReadAllText(ConfigPath); } catch { }
            if (current != _written) _written = "";
            WriteIfNeeded();
        }
    }

    // MARK: 提示语分类（askpass 和内置 SSH 共用）

    public enum PromptKind { HostKey, Passphrase, OneTimeCode, Password, Username, Other }

    public static PromptKind Kind(string prompt)
    {
        var lower = prompt.ToLowerInvariant();
        if (lower.Contains("yes/no") || lower.Contains("fingerprint")) return PromptKind.HostKey;
        if (lower.Contains("passphrase")) return PromptKind.Passphrase;
        if (lower.Contains("username") || lower.Contains("user name") || lower.Contains("用户名")) return PromptKind.Username;
        if (new[] { "code", "token", "otp", "verification", "authenticator", "验证码", "动态" }.Any(lower.Contains)) return PromptKind.OneTimeCode;
        if (lower.Contains("password") || lower.Contains("密码")) return PromptKind.Password;
        return PromptKind.Other;
    }
}
