    public static PendingReason? Explain(string? raw)
    {
        var r = raw?.Trim(' ', '\t');
        if (string.IsNullOrEmpty(r)) return null;
        foreach (var e in Table)
        {
            if (r.StartsWith(e.Key, StringComparison.Ordinal)
                || (e.Key.Length > 12 && r.Contains(e.Key, StringComparison.OrdinalIgnoreCase)))
                return new PendingReason(L(e.ShortZh, e.ShortEn), L(e.LongZh, e.LongEn) + $"\n（Slurm：{r}）", e.Act);
        }
        return new PendingReason(r.Prefix(28), r, false);
    }
